const RULE = /^(\d\d-\d\d|[EO](?:[+-]\d+)?)$/;
const en = {};
const byLang = {};
let rows = 0;
for (const [cc, lang, tz, days] of COUNTRIES) {
  const seen = new Set();
  for (const [id, rule, enName, native] of days) {
    if (!RULE.test(rule)) throw new Error(`bad rule ${cc}.${id}: ${rule}`);
    if (seen.has(id)) throw new Error(`duplicate ${cc}.${id}`);
    seen.add(id);
    en[`${cc}.${id}`] = enName;
    (byLang[lang] ??= {})[`${cc}.${id}`] = native;
    rows++;
  }
}

fs.mkdirSync(`${ROOT}/holidays`, { recursive: true });
fs.writeFileSync(`${ROOT}/holidays/en.json`, JSON.stringify(en, null, 2) + "\n");
for (const [lang, dict] of Object.entries(byLang)) {
  fs.writeFileSync(`${ROOT}/holidays/${lang}.json`, JSON.stringify(dict, null, 2) + "\n");
}

// The COUNTRIES block of events.js
const lines = COUNTRIES.map(([cc, lang, tz, days]) => {
  const list = days.map(([id, rule]) => `['${id}', '${rule}']`).join(", ");
  return `  ${cc}: { lang: '${lang}', tz: '${tz}', days: [${list}] },`;
});
const block = `  const COUNTRIES = {\n${lines.join("\n")}\n  };`;
const file = `${ROOT}/events.js`;
let src = fs.readFileSync(file, "utf8");
const re = /  const COUNTRIES = \{\};|  const COUNTRIES = \{\n[\s\S]*?\n  \};/;
if (!re.test(src)) throw new Error("COUNTRIES block not found in events.js");
src = src.replace(re, block);
fs.writeFileSync(file, src);

