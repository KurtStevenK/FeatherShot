  // A rule is 'MM-DD' (a fixed date), 'E+n' (Western Easter plus n days) or 'O+n' (Orthodox Easter plus n days).
  function utc(y, m, d) {
    return new Date(Date.UTC(y, m - 1, d));
  }

  function addDays(date, n) {
    return new Date(date.getTime() + n * 86400000);
  }

  function ymd(date) {
    return date.toISOString().slice(0, 10);
  }

  // Western (Gregorian) Easter Sunday: the anonymous algorithm.
  function easterWestern(year) {
    const a = year % 19;
    const b = Math.floor(year / 100);
    const c = year % 100;
    const d = Math.floor(b / 4);
    const e = b % 4;
    const f = Math.floor((b + 8) / 25);
    const g = Math.floor((b - f + 1) / 3);
    const h = (19 * a + b - d - g + 15) % 30;
    const i = Math.floor(c / 4);
    const k = c % 4;
    const l = (32 + 2 * e + 2 * i - h - k) % 7;
    const m = Math.floor((a + 11 * h + 22 * l) / 451);
    const month = Math.floor((h + l - 7 * m + 114) / 31);
    const day = ((h + l - 7 * m + 114) % 31) + 1;
    return utc(year, month, day);
  }

  // Orthodox Easter Sunday: the Julian computus, plus 13 days (valid for 1900 to 2099).
  function easterOrthodox(year) {
    const a = year % 4;
    const b = year % 7;
    const c = year % 19;
    const d = (19 * c + 15) % 30;
    const e = (2 * a + 4 * b - d + 34) % 7;
    const month = Math.floor((d + e + 114) / 31);
    const day = ((d + e + 114) % 31) + 1;
    return addDays(utc(year, month, day), 13);
  }

  // The date of a rule in a year, as 'YYYY-MM-DD'.
  function ruleYmd(rule, year) {
    const fixed = /^(\d\d)-(\d\d)$/.exec(rule);
    if (fixed) return year + '-' + fixed[1] + '-' + fixed[2];
    const advent = /^A([1-4])$/.exec(rule);
    if (advent) {
      // The 4th Advent is the last Sunday before Christmas Day; the others are a week apart.
      const eve = utc(year, 12, 24);
      const fourth = addDays(eve, -eve.getUTCDay());
      return ymd(addDays(fourth, -7 * (4 - Number(advent[1]))));
    }
    const moving = /^([EO])([+-]\d+)?$/.exec(rule);
    if (!moving) return null;
    const base = moving[1] === 'E' ? easterWestern(year) : easterOrthodox(year);
    return ymd(addDays(base, Number(moving[2] || 0)));
  }

  const dayFormats = {};

  // The calendar date in a time zone, as 'YYYY-MM-DD' (the 'en-CA' locale writes it that way).
  function localYmd(tz, now) {
    if (!dayFormats[tz]) {
      dayFormats[tz] = new Intl.DateTimeFormat('en-CA', { timeZone: tz, year: 'numeric', month: '2-digit', day: '2-digit' });
    }
    return dayFormats[tz].format(new Date(now));
  }

  // The holiday of country cc today: { id: 'AT.neujahr', cc: 'AT' }, or null.
  function holidayToday(cc, now) {
    const country = COUNTRIES[cc];
    if (!country) return null;
    const today = localYmd(country.tz, now);
    const year = Number(today.slice(0, 4));
    for (const day of country.days) {
      if (ruleYmd(day[1], year) === today) return { id: cc + '.' + day[0], cc: cc };
    }
    return null;
  }

  // The country for the chosen UI language and the browser's language list (de-CH gives CH).
  function countryFor(uiLang, navLangs) {
    for (const tag of navLangs || []) {
      const parts = String(tag).split('-');
      const region = (parts[1] || '').toUpperCase();
      if (parts[0].toLowerCase() === uiLang && COUNTRIES[region]) return region;
    }
    return LANG_COUNTRY[uiLang] || null;
  }

  // The season event of today for country cc (null: no country), or null.
  function seasonToday(cc, now) {
    const tz = cc && COUNTRIES[cc] ? COUNTRIES[cc].tz : 'Europe/Vienna';
    const today = localYmd(tz, now);
    const year = Number(today.slice(0, 4));
    for (const s of SEASON) {
      if (s.only && s.only.indexOf(cc) < 0) continue;
      if (s.not && s.not.indexOf(cc) >= 0) continue;
      if (ruleYmd(s.rule, year) === today) return s;
    }
    return null;
  }

  // The badge that applies now, or null: a promo first, then a season event, then a public holiday.
  // overrides: { 'cyber-monday': instant } moves an end.
  function activeBadge(now, cc, overrides) {
    for (const p of PROMOS) {
      const until = overrides && overrides[p.id] ? overrides[p.id] : p.until;
      if (now >= p.from && now < until) return { kind: 'promo', id: p.id, label: p.label };
    }
    const season = seasonToday(cc, now);
    if (season) return { kind: 'season', id: season.id, key: season.key, label: season.label };
    const holiday = cc ? holidayToday(cc, now) : null;
    if (holiday) return { kind: 'holiday', id: holiday.id, cc: cc };
    return null;
  }

